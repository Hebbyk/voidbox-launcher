"""
make_key.py - run this ONCE on your PC to bake your CurseForge API key into the app.

    py make_key.py

It asks for the key (input is hidden - paste with right-click or Ctrl+V, nothing will show),
then writes _cfk.py next to it. build.ps1 / voidbox.spec pick _cfk.py up automatically.
Re-run it any time you get a new key. Never share or upload _cfk.py.

The key is stored XOR-scrambled and split into pieces, so it can't be found by searching
the exe for text. This stops casual extraction only - a network sniffer can still see it.
"""
import base64
import getpass
import os
import sys


def _chunks(b: bytes, n: int):
    step = -(-len(b) // n)
    return [base64.b85encode(b[i:i + step]).decode() for i in range(0, len(b), step)]


def main():
    key = getpass.getpass("Paste your CurseForge API key (hidden): ").strip()
    if len(key) < 20:
        sys.exit("That doesn't look like a CurseForge key (too short). Nothing written.")
    pad = os.urandom(len(key.encode()))
    data = bytes(a ^ b for a, b in zip(key.encode(), pad))
    # pieces are stored in shuffled order; _ORDER restores it
    a, b = _chunks(data, 3), _chunks(pad, 3)
    order = [2, 0, 1]
    out = (
        '"""Generated by make_key.py - do not edit, do not share."""\n'
        "import base64 as _b\n"
        f"_D = {[a[i] for i in order]!r}\n"
        f"_P = {[b[i] for i in order]!r}\n"
        f"_O = {order!r}\n\n\n"
        "def get():\n"
        "    d = [None] * len(_O); p = [None] * len(_O)\n"
        "    for pos, idx in enumerate(_O):\n"
        "        d[idx] = _b.b85decode(_D[pos]); p[idx] = _b.b85decode(_P[pos])\n"
        "    d, p = b''.join(d), b''.join(p)\n"
        "    return bytes(x ^ y for x, y in zip(d, p)).decode()\n"
    )
    here = os.path.dirname(os.path.abspath(__file__))
    with open(os.path.join(here, "_cfk.py"), "w", encoding="utf-8") as f:
        f.write(out)
    # self-check: read it back exactly as the app will
    sys.path.insert(0, here)
    import _cfk
    if _cfk.get() != key:
        sys.exit("Self-check FAILED - _cfk.py does not round-trip. Do not use it.")
    print(f"OK - wrote _cfk.py ({len(key)}-char key, round-trip verified). Now run .\\build.ps1")


if __name__ == "__main__":
    main()
